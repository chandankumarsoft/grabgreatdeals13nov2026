               url: "<?php echo base_url(); ?>add-wishlist",
               method: "POST",
               data:{wishlist_pro_id:wishlist_pro_id},
               dataType: "json",
               success: function (response) {
                  if (response.cus_status=='not_log_in') {
                     swal("You Are Not Logged In");
                  }
                  if (response.wishlist_added=='success') {
                     swal("Added to your Wishlist","","success");
                  }
                  if (response.wishlist_already_register=='already_registered') {
                     swal("Already Added to your Wishlist","", "error");
                  }
               }
         });
      });
   });
</script>
