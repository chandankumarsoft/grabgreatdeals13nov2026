   $(document).ready(function(){
   $(".idNewsLettersForm").submit(function(e) {
   
   e.preventDefault(); 
   
   var form = $(this); 
   var url = form.attr('action');
   $.ajax({
        type: "POST",
        url: url,
        data: form.serialize(), 
        dataType:"json",
        success: function(data)
        {
          if (data.error_msg=="success") {
            $('#error_msg_validation_msg').html('');
            swal("Added to your Newsletter Successfully","","success");
          }
          if (data.error_msg_validation) {
            $('#error_msg_validation_msg').html(data.error_msg_validation);
          }
        }
      });
   
   
   });
   });
</script>
<script>
   $(document).ready(function(){
      $(".wishlist_value_class").on("click", function(){
         var wishlist_pro_id = $(this).attr("data-value");
